package me.rerere.workspace

import java.io.File
import java.nio.file.Files
import java.util.concurrent.TimeUnit

class RootfsPatcher(
    private val systemDnsProvider: () -> List<String> = ::readHostSystemDns,
) {
    // patch() 每次命令都跑：同一把锁串行化 check-then-append，
    // 避免并发命令对 hosts/group 重复追加同一行
    private val patchLock = Any()

    fun patch(
        linuxDir: File,
        options: RootfsPatchOptions = RootfsPatchOptions(),
    ) {
        synchronized(patchLock) {
            val etcDir = File(linuxDir, "etc")
            if (!etcDir.isDirectory) return

            ensureRootfsDns(etcDir, options.nameservers)
            ensureHosts(etcDir, options.hostname)
            ensureHostname(etcDir, options.hostname)
            ensureLocale(etcDir, options.locale)
            ensureGroupNames(etcDir, options.groupIds.ifEmpty { currentSupplementaryGroupIds() })
            ensureTempDirs(linuxDir)
        }
    }

    private fun ensureRootfsDns(
        etcDir: File,
        nameservers: List<String>,
    ) {
        val resolvConf = File(etcDir, "resolv.conf")
        val path = resolvConf.toPath()
        val isSymlink = Files.isSymbolicLink(path)
        if (isSymlink || (resolvConf.exists() && !resolvConf.isFile)) {
            runCatching { Files.deleteIfExists(path) }
            resolvConf.delete()
        }

        val customServers = ShellDnsConfig.parseServers(nameservers.joinToString("\n"))
        if (customServers.isNotEmpty()) {
            writeResolvConf(resolvConf, customServers, mode = ShellDnsConfig.MODE_CUSTOM)
            return
        }

        // Auto mode: prefer live host system DNS (excluding loopback/unspecified),
        // falling back to DEFAULT_DNS_SERVERS when system DNS is unavailable.
        val systemServers =
            runCatching { systemDnsProvider() }
                .getOrDefault(emptyList())
                .let { ShellDnsConfig.parseServers(it.joinToString("\n")) }
                .take(MAX_DNS_SERVERS)

        if (systemServers.isNotEmpty()) {
            writeResolvConf(resolvConf, systemServers, mode = ShellDnsConfig.MODE_AUTO)
            return
        }

        val existingText = if (resolvConf.isFile) runCatching { resolvConf.readText() }.getOrDefault("") else ""
        val wasCustomGenerated = existingText.contains("mode=custom")
        val hasValidExisting =
            !wasCustomGenerated &&
                existingText
                    .lineSequence()
                    .filter { it.trimStart().startsWith("nameserver ") }
                    .any { line ->
                        val server = line.trim().removePrefix("nameserver").trim()
                        server.isNotBlank() && server !in LOCAL_RESOLVERS && ShellDnsConfig.isValidDnsIp(server)
                    }
        if (hasValidExisting) return

        writeResolvConf(resolvConf, DEFAULT_DNS_SERVERS.take(MAX_DNS_SERVERS), mode = ShellDnsConfig.MODE_AUTO)
    }

    private fun writeResolvConf(
        resolvConf: File,
        servers: List<String>,
        mode: String,
    ) {
        if (Files.isSymbolicLink(resolvConf.toPath())) {
            runCatching { Files.deleteIfExists(resolvConf.toPath()) }
        }
        // 纵深校验：只写合法 DNS IP，非法串绝不进 resolv.conf
        val validServers = servers.filter { ShellDnsConfig.isValidDnsIp(it) }
        resolvConf.writeText(
            buildString {
                appendLine("# Generated by RikkaHub workspace (mode=$mode).")
                validServers.forEach { appendLine("nameserver $it") }
                // Fail over to the next server after 2 s instead of the 5 s default.
                appendLine("options timeout:2 attempts:2 rotate edns0 trust-ad")
            },
        )
    }

    /** 目标是软链时先删链接再写普通文件，不跟随写到 rootfs 外（与 resolv.conf 同口径）。 */
    private fun removeSymlinkIfPresent(file: File) {
        if (Files.isSymbolicLink(file.toPath())) {
            runCatching { Files.deleteIfExists(file.toPath()) }
        }
    }

    private fun ensureHosts(
        etcDir: File,
        hostname: String,
    ) {
        val hosts = File(etcDir, "hosts")
        removeSymlinkIfPresent(hosts)
        val lines = if (hosts.isFile) hosts.readLines() else emptyList()
        val hasIpv4Localhost =
            lines.any { line ->
                val normalized = line.substringBefore('#').trim().split(WHITESPACE_REGEX)
                normalized.firstOrNull() == "127.0.0.1" && "localhost" in normalized.drop(1)
            }
        val hasIpv6Localhost =
            lines.any { line ->
                val normalized = line.substringBefore('#').trim().split(WHITESPACE_REGEX)
                normalized.firstOrNull() == "::1" && "localhost" in normalized.drop(1)
            }
        if (hasIpv4Localhost && hasIpv6Localhost) return

        hosts.parentFile?.mkdirs()
        hosts.appendText(
            buildString {
                if (hosts.exists() && hosts.length() > 0 && !hosts.readText().endsWith('\n')) {
                    appendLine()
                }
                if (!hasIpv4Localhost) {
                    append("127.0.0.1 localhost")
                    if (hostname.isNotBlank() && hostname != "localhost") {
                        append(" ")
                        append(hostname)
                    }
                    appendLine()
                }
                if (!hasIpv6Localhost) {
                    appendLine("::1 localhost ip6-localhost ip6-loopback")
                }
            },
        )
    }

    private fun ensureHostname(
        etcDir: File,
        hostname: String,
    ) {
        val target = File(etcDir, "hostname")
        removeSymlinkIfPresent(target)
        if (target.isFile && target.readText().trim().isNotBlank()) return
        target.writeText("${hostname.ifBlank { DEFAULT_HOSTNAME }}\n")
    }

    private fun ensureLocale(
        etcDir: File,
        locale: String,
    ) {
        val defaultDir = File(etcDir, "default").apply { mkdirs() }
        val target = File(defaultDir, "locale")
        removeSymlinkIfPresent(target)
        val lines = if (target.isFile) target.readLines().toMutableList() else mutableListOf()
        if (lines.any { it.trim().startsWith("LANG=") }) return
        lines += "LANG=$locale"
        target.writeText(lines.joinToString(separator = "\n", postfix = "\n"))
    }

    private fun ensureGroupNames(
        etcDir: File,
        groupIds: List<Long>,
    ) {
        val target = File(etcDir, "group")
        removeSymlinkIfPresent(target)
        if (!target.exists()) {
            target.writeText("root:x:0:\n")
        }
        val lines = target.readLines().toMutableList()
        val existingIds =
            lines
                .mapNotNull { line ->
                    line.split(':').getOrNull(2)?.toLongOrNull()
                }.toSet()
        val existingNames =
            lines
                .mapNotNull { line ->
                    line.substringBefore(':').takeIf { it.isNotBlank() }
                }.toSet()
        val additions =
            groupIds
                .filter { it > 0 && it !in existingIds }
                .distinct()
                .map { id ->
                    val baseName = "android_gid_$id"
                    val name = if (baseName in existingNames) "${baseName}_workspace" else baseName
                    "$name:x:$id:"
                }
        if (additions.isEmpty()) return

        target.appendText(
            buildString {
                if (target.length() > 0 && !target.readText().endsWith('\n')) {
                    appendLine()
                }
                additions.forEach { appendLine(it) }
            },
        )
    }

    private fun ensureTempDirs(linuxDir: File) {
        listOf("tmp", "var/tmp", "root").forEach { path ->
            File(linuxDir, path).mkdirs()
        }
        listOf(File(linuxDir, "tmp"), File(linuxDir, "var/tmp")).forEach { dir ->
            dir.setReadable(true, false)
            dir.setWritable(true, false)
            dir.setExecutable(true, false)
            // /tmp 须为 1777（带粘滞位）：Java File API 设不了粘滞位，用 chmod 补；
            // 0777 无粘滞位时任一用户可删他人文件
            runCatching {
                val chmod = File("/system/bin/chmod").takeIf { it.canExecute() } ?: File("/bin/chmod")
                val proc = ProcessBuilder(chmod.absolutePath, "1777", dir.absolutePath).start()
                proc.waitFor(2, TimeUnit.SECONDS)
            }
        }
        File(linuxDir, "root").apply {
            setReadable(true, true)
            setWritable(true, true)
            setExecutable(true, true)
        }
    }

    private fun currentSupplementaryGroupIds(): List<Long> {
        val status = File("/proc/self/status")
        if (!status.isFile) return emptyList()
        val groups = status.readLines().firstOrNull { it.startsWith("Groups:") } ?: return emptyList()
        return groups
            .removePrefix("Groups:")
            .trim()
            .split(WHITESPACE_REGEX)
            .mapNotNull { it.toLongOrNull() }
    }

    companion object {
        private const val MAX_DNS_SERVERS = 6
        private const val DEFAULT_HOSTNAME = "localhost"
        private val WHITESPACE_REGEX = Regex("\\s+")
        private val LOCAL_RESOLVERS =
            setOf(
                "127.0.0.1",
                "127.0.0.53",
                "::1",
            )
        // Public anycast resolvers first (wide global coverage, low first-query
        // latency), then a last-resort global fallback.
        internal val DEFAULT_DNS_SERVERS =
            listOf(
                "223.5.5.5",
                "119.29.29.29",
                "8.8.8.8",
            )

        internal fun readHostSystemDns(): List<String> {
            val discovered = LinkedHashSet<String>()
            val pnp = File("/proc/net/pnp")
            if (pnp.isFile && pnp.canRead()) {
                runCatching {
                    pnp.readLines().forEach { line ->
                        val trimmed = line.trim()
                        if (trimmed.startsWith("nameserver ")) {
                            val ip = trimmed.removePrefix("nameserver").trim()
                            if (ip !in LOCAL_RESOLVERS && ShellDnsConfig.isValidDnsIp(ip)) {
                                discovered.add(ip)
                            }
                        }
                    }
                }
            }
            if (discovered.isEmpty()) {
                val getprop = File("/system/bin/getprop")
                if (getprop.isFile && getprop.canExecute()) {
                    for (prop in listOf("net.dns1", "net.dns2", "net.dns3", "net.dns4")) {
                        runCatching {
                            val proc = ProcessBuilder(getprop.absolutePath, prop).start()
                            val finished = proc.waitFor(500, TimeUnit.MILLISECONDS)
                            if (finished && proc.exitValue() == 0) {
                                val ip = proc.inputStream.bufferedReader().readText().trim()
                                if (ip !in LOCAL_RESOLVERS && ShellDnsConfig.isValidDnsIp(ip)) {
                                    discovered.add(ip)
                                }
                            } else {
                                proc.destroyForcibly()
                            }
                        }
                    }
                }
            }
            return discovered.toList()
        }
    }
}

data class RootfsPatchOptions(
    val nameservers: List<String> = emptyList(),
    val hostname: String = "localhost",
    val locale: String = "C.UTF-8",
    val groupIds: List<Long> = emptyList(),
)
